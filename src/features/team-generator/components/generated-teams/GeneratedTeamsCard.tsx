"use client";

import { useMemo, useRef } from "react";
import {
  Card,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { useTeamGeneratorStore } from "@/features/team-generator/store/use-team-generator-store";
import { getGeneratedTeamsText } from "../../utils/get-generated-teams-text";
import { CopyButton } from "./CopyButton";
import { DownloadButton } from "./DownloadButton";
import { GeneratedTeamCard } from "./GeneratedTeamCard";
import { ShareButton } from "./ShareButton";

type GeneratedTeamsCardProps = {
  title?: string;
};

export function GeneratedTeamsCard({
  title = "Generated Teams",
}: GeneratedTeamsCardProps) {
  const players = useTeamGeneratorStore((state) => state.players);
  const generationResult = useTeamGeneratorStore(
    (state) => state.generationResult,
  );

  const shareContentRef = useRef<HTMLDivElement>(null);

  // Create a map of player IDs to their placeholder numbers for display purposes.
  const placeholderPlayerNumberMap = useMemo(
    () => new Map(players.map((player, index) => [player.id, index + 1])),
    [players],
  );

  if (!generationResult) {
    return null;
  }

  // Dates persisted by Zustand are serialized as strings and must be converted to Date objects before formatting.
  const generatedAt = new Date(generationResult.generatedAt);

  const generatedTeamsText = getGeneratedTeamsText(
    generationResult.teams,
    generatedAt,
    placeholderPlayerNumberMap,
  );

  return (
    <section aria-label="Generated Teams" ref={shareContentRef}>
      <Card
        key={generationResult.id}
        className="animate-in fade-in duration-400 motion-reduce:animate-none"
      >
        <CardHeader>
          <CardTitle
            id="generated-teams-heading"
            className="text-center text-2xl font-semibold tracking-tight"
          >
            {title}
          </CardTitle>

          <CardDescription className="text-center">
            Teams generated by Ball+ on {generatedAt.toLocaleString()}
          </CardDescription>
        </CardHeader>

        <CardContent className="grid gap-4 md:grid-cols-2">
          {generationResult.teams.map((generatedTeam, index) => (
            <GeneratedTeamCard
              key={generatedTeam.team.id}
              generatedTeam={generatedTeam}
              teamIndex={index}
              placeholderPlayerNumberMap={placeholderPlayerNumberMap}
            />
          ))}
        </CardContent>

        <CardFooter
          data-share-exclude
          className="justify-center sm:justify-end gap-4"
        >
          <CopyButton text={generatedTeamsText} />
          <ShareButton targetRef={shareContentRef} generatedAt={generatedAt} />
          <DownloadButton
            targetRef={shareContentRef}
            generatedAt={generatedAt}
          />
        </CardFooter>
      </Card>
    </section>
  );
}
