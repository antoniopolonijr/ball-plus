"use client";

import { Share2 } from "lucide-react";
import { useMemo } from "react";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { useTeamGeneratorStore } from "../../store/team-generator-store";
import { getGeneratedTeamsText } from "../../utils/get-generated-teams-text";
import { CopyButton } from "./CopyButton";
import { GeneratedTeamCard } from "./GeneratedTeamCard";

export function GeneratedTeamsCard() {
  const players = useTeamGeneratorStore((state) => state.players);
  const generationResult = useTeamGeneratorStore(
    (state) => state.generationResult,
  );

  // Create a map of player IDs to their placeholder numbers for display purposes.
  const placeholderPlayerNumberMap = useMemo(
    () => new Map(players.map((player, index) => [player.id, index + 1])),
    [players],
  );

  if (!generationResult) {
    return null;
  }

  // Dates persisted by Zustand are serialized as strings and must be converted to Date objects before formatting.
  const generatedAt = new Date(generationResult.generatedAt);

  const generatedTeamsText = getGeneratedTeamsText(
    generationResult.teams,
    generatedAt,
    placeholderPlayerNumberMap,
  );

  return (
    <section aria-labelledby="generated-team-heading">
      <Card>
        <CardHeader>
          <CardTitle
            id="generated-team-heading"
            className="text-center text-2xl tracking-tight font-semibold"
          >
            Generated Teams
          </CardTitle>

          <CardDescription className="text-center">
            Teams generated by Ball+ on {generatedAt.toLocaleString()}
          </CardDescription>
        </CardHeader>

        <CardContent className="grid gap-4 md:grid-cols-2">
          {generationResult.teams.map((generatedTeam, index) => (
            <GeneratedTeamCard
              key={generatedTeam.team.id}
              generatedTeam={generatedTeam}
              teamIndex={index}
              placeholderPlayerNumberMap={placeholderPlayerNumberMap}
            />
          ))}
        </CardContent>
        <CardFooter className="justify-center gap-4">
          <CopyButton text={generatedTeamsText} />

          <Button aria-label="Share Generated Teams">
            <Share2 className="size-4" aria-hidden="true" />
            Share
          </Button>
        </CardFooter>
      </Card>
    </section>
  );
}
