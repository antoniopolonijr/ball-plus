"use client";

import { Share2, Copy } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";

import { useTeamGeneratorStore } from "../../store/team-generator-store";
import { GeneratedTeamTable } from "./GeneratedTeamTable";

export function GeneratedTeamsCard() {
  const generationResult = useTeamGeneratorStore(
    (state) => state.generationResult,
  );

  if (!generationResult) {
    return null;
  }

  return (
    <section aria-labelledby="generated-team-heading">
      <Card>
        <CardHeader>
          <CardTitle
            id="generated-team-heading"
            className="text-center text-2xl tracking-tight font-semibold"
          >
            Generated Teams
          </CardTitle>

          <CardDescription className="text-center">
            Teams generated by Ball+ on{" "}
            {generationResult.generatedAt.toLocaleString()}
          </CardDescription>
        </CardHeader>

        <CardContent className="grid gap-4 md:grid-cols-2">
          {generationResult.teams.map((generatedTeam, index) => (
            <GeneratedTeamTable
              key={generatedTeam.team.id}
              generatedTeam={generatedTeam}
              index={index}
            />
          ))}
        </CardContent>
        <CardFooter className="justify-center gap-4">
          <Button aria-label="Copy Generated Teams">
            <Copy className="size-4" aria-hidden="true" />
            Copy
          </Button>
          <Button aria-label="Share Generated Teams">
            <Share2 className="size-4" aria-hidden="true" />
            Share
          </Button>
        </CardFooter>
      </Card>
    </section>
  );
}
